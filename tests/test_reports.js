const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/../reports-core.js','utf8');
const ctx={console,Date,Intl,globalThis:null};ctx.globalThis=ctx;vm.runInNewContext(source,ctx);
const core=ctx.OGE_REPORTS_CORE;
const weekly=core.weeklyPeriod(new Date('2026-10-19T05:00:00.000Z'));
assert.equal(weekly.key,'2026-10-12');
assert.equal(weekly.start,'2026-10-11T19:00:00.000Z');
assert.equal(weekly.end,'2026-10-18T19:00:00.000Z');
const monthly=core.monthlyPeriod(new Date('2026-11-01T05:05:00.000Z'));
assert.equal(monthly.key,'2026-10-01');
assert.equal(monthly.start,'2026-09-30T19:00:00.000Z');
assert.equal(monthly.previous.start,'2026-08-31T19:00:00.000Z');
const items=[{id:'a',domain:'Грамматика',topic:'Present Simple',correct:false},{id:'b',domain:'Словарь',topic:'Family',correct:true}];
const events=[{id:'e1',type:'lesson',date:'2026-10-13T10:00:00.000Z',passed:true,topic:'Present Simple',week:1,session:1,items},{id:'e2',type:'lesson',date:'2026-10-16T11:00:00.000Z',passed:false,topic:'Family',week:1,session:2,items}];
const report=core.weeklyReport(events,new Date('2026-10-19T05:00:00.000Z'));
assert(report.text.includes('Учебные дни: 2/3'));
assert(report.text.includes('Грамматика: Present Simple'));
assert(report.text.includes('Словарь: Family')===false);
assert(!core.monthlyReport(events,new Date('2026-11-01T05:05:00Z')).text.includes('Результат вырос на'));
console.log('OK: weekly/monthly boundaries, domain errors, minimum sample check');
